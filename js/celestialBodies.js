/*
Remove accidental duplicates by name.
*/

export const allCelestialObjects =
    celestialObjects.filter(
        (object, index, array) =>
            array.findIndex(
                item =>
                    item.name === object.name
            ) === index
    );


/* =========================================================
   GET OBJECT
========================================================= */

export function getCelestialObject(name) {

    if (!name) {
        return null;
    }

    const normalized =
        String(name)
            .trim()
            .toLowerCase();

    return allCelestialObjects.find(
        object =>
            object.name
                .toLowerCase() === normalized
    ) || null;
}


/* =========================================================
   GET ALL
========================================================= */

export function getCelestialObjectList() {

    return [
        ...allCelestialObjects
    ];
}


/* =========================================================
   GET BY TYPE
========================================================= */

export function getObjectsByType(type) {

    if (!type) {
        return [];
    }

    const normalized =
        String(type)
            .trim()
            .toLowerCase();

    return allCelestialObjects.filter(
        object =>
            object.type
                .toLowerCase() === normalized
    );
}


/* =========================================================
   SEARCH
========================================================= */

export function searchCelestialObjects(query) {

    if (!query) {
        return [];
    }

    const normalized =
        String(query)
            .trim()
            .toLowerCase();

    return allCelestialObjects.filter(
        object =>
            object.name
                .toLowerCase()
                .includes(normalized)
    );
}


