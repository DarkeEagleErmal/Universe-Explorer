/* =========================================================
   HELPER
========================================================= */

function createBody(data) {
    return {
        name: data.name,
        type: data.type,

        position: data.position || [0, 0, 0],

        radius: data.radius || 1,
        color: data.color || 0xffffff,

        size: data.size || "Unknown",
        mass: data.mass || "Unknown",
        temperature: data.temperature || "Unknown",
        gravity: data.gravity || "Unknown",

        composition: data.composition || "Unknown",
        atmosphere: data.atmosphere || "None",

        rotation: data.rotation || "Unknown",
        orbit: data.orbit || "Unknown",

        textureStyle: data.textureStyle || "rocky",

        atmosphereColor:
            data.atmosphereColor || data.color || 0xffffff,

        hasAtmosphere:
            data.hasAtmosphere || false,

        hasRings:
            data.hasRings || false,

        parent:
            data.parent || null,

        facts:
            data.facts || []
    };
}


